//! HTTP layers shared by the public and admin servers.
//!
//! From the outside in: security headers (`security.rs`, §14.2), sensitive headers marking,
//! request id, tracing, panic catching, compression, JSON error bodies, timeout and body size
//! limit.
//!
//! Tracing records the method, the **route template** (never the concrete URI, which may hold
//! a tracking token or a search text), the status and the latency. No header, IP or body is
//! logged (§7.1).

use std::any::Any;

use axum::Router;
use axum::body::Body;
use axum::extract::{DefaultBodyLimit, MatchedPath, Request};
use axum::http::{HeaderName, HeaderValue, StatusCode, header};
use axum::middleware::{self, Next};
use axum::response::{IntoResponse, Response};
use tower_http::LatencyUnit;
use tower_http::catch_panic::CatchPanicLayer;
use tower_http::classify::ServerErrorsFailureClass;
use tower_http::compression::CompressionLayer;
use tower_http::limit::RequestBodyLimitLayer;
use tower_http::sensitive_headers::SetSensitiveRequestHeadersLayer;
use tower_http::timeout::TimeoutLayer;
use tower_http::trace::{DefaultOnResponse, TraceLayer};
use tracing::{Level, Span};

use super::error::ApiError;
use super::security::{self, Surface};
use crate::config::HttpConfig;

pub const REQUEST_ID_HEADER: HeaderName = HeaderName::from_static("x-request-id");

/// Identifier of the current request, generated by the server (client values are ignored).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct RequestId(pub String);

/// Generates a request id, exposes it to handlers (extension) and to the client (header).
pub async fn request_id(mut request: Request, next: Next) -> Response {
    let id = uuid::Uuid::new_v4().to_string();
    request.headers_mut().remove(&REQUEST_ID_HEADER);
    request.extensions_mut().insert(RequestId(id.clone()));
    let mut response = next.run(request).await;
    if let Ok(value) = HeaderValue::from_str(&id) {
        response.headers_mut().insert(REQUEST_ID_HEADER, value);
    }
    response
}

/// Replaces non-JSON error bodies (404 of the router, 405, 408/504 timeouts, 413 body limit,
/// axum rejections…) by the unified JSON error.
pub async fn json_errors(request: Request, next: Next) -> Response {
    let response = next.run(request).await;
    let status = response.status();
    if !(status.is_client_error() || status.is_server_error()) {
        return response;
    }
    let is_json = response
        .headers()
        .get(header::CONTENT_TYPE)
        .and_then(|value| value.to_str().ok())
        .is_some_and(|value| value.starts_with("application/json"));
    if is_json {
        return response;
    }
    let mut replaced = ApiError::from_status(status).into_response();
    for name in [header::ALLOW, header::RETRY_AFTER, header::WWW_AUTHENTICATE] {
        if let Some(value) = response.headers().get(&name) {
            replaced.headers_mut().insert(name, value.clone());
        }
    }
    replaced
}

fn panic_response(_panic: Box<dyn Any + Send + 'static>) -> Response {
    // The payload may quote request data: do not log it.
    tracing::error!("request handler panicked");
    ApiError::internal().into_response()
}

fn make_span(request: &axum::http::Request<Body>) -> Span {
    let route = request
        .extensions()
        .get::<MatchedPath>()
        .map_or("unmatched", MatchedPath::as_str);
    let request_id = request
        .extensions()
        .get::<RequestId>()
        .map_or("", |id| id.0.as_str());
    tracing::info_span!(
        "http_request",
        method = %request.method(),
        route,
        request_id,
    )
}

/// Level of a failed response: `503` is an expected, temporary answer (exports not generated
/// yet, service saturated or unavailable, each logged where it is decided), so it is a warning;
/// any other server error (`500`, `504`, a failed body) is an error.
fn failure_level(class: &ServerErrorsFailureClass) -> Level {
    match class {
        ServerErrorsFailureClass::StatusCode(status)
            if *status == StatusCode::SERVICE_UNAVAILABLE =>
        {
            Level::WARN
        }
        _ => Level::ERROR,
    }
}

/// Logs a failed response inside the request span (route template and request id only).
fn log_failure(class: ServerErrorsFailureClass, latency: std::time::Duration, _span: &Span) {
    let latency = format!("{} ms", latency.as_millis());
    if failure_level(&class) == Level::WARN {
        tracing::warn!(classification = %class, latency, "response failed");
    } else {
        tracing::error!(classification = %class, latency, "response failed");
    }
}

/// Wraps a router with the shared layers; `surface` selects the `Cache-Control` policy of the
/// security headers.
pub fn with_common_layers(router: Router, config: &HttpConfig, surface: Surface) -> Router {
    router
        .layer(RequestBodyLimitLayer::new(config.body_limit_bytes))
        .layer(DefaultBodyLimit::max(config.body_limit_bytes))
        .layer(TimeoutLayer::with_status_code(
            StatusCode::GATEWAY_TIMEOUT,
            config.request_timeout,
        ))
        .layer(middleware::from_fn(json_errors))
        .layer(CompressionLayer::new())
        .layer(CatchPanicLayer::custom(panic_response))
        .layer(
            TraceLayer::new_for_http()
                .make_span_with(make_span)
                .on_request(())
                .on_response(
                    DefaultOnResponse::new()
                        .level(Level::INFO)
                        .latency_unit(LatencyUnit::Millis),
                )
                .on_failure(log_failure),
        )
        .layer(middleware::from_fn(request_id))
        .layer(SetSensitiveRequestHeadersLayer::new([
            header::AUTHORIZATION,
            header::COOKIE,
            HeaderName::from_static("x-forwarded-for"),
        ]))
        .layer(middleware::from_fn_with_state(
            surface,
            security::security_headers,
        ))
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::config::{Config, Role};
    use axum::routing::{get, post};
    use http_body_util::BodyExt;
    use std::time::Duration;
    use tower::ServiceExt;

    fn http_config() -> HttpConfig {
        let mut config = Config::from_lookup(Role::Worker, |key| {
            (key == "DATABASE_CONNECTION_STRING").then(|| "postgres://unused/db".to_owned())
        })
        .unwrap()
        .http;
        config.request_timeout = Duration::from_millis(200);
        config.body_limit_bytes = 1024;
        config
    }

    #[test]
    fn only_unexpected_server_errors_are_logged_as_errors() {
        let class = |status| ServerErrorsFailureClass::StatusCode(status);
        assert_eq!(
            failure_level(&class(StatusCode::SERVICE_UNAVAILABLE)),
            Level::WARN
        );
        for status in [
            StatusCode::INTERNAL_SERVER_ERROR,
            StatusCode::BAD_GATEWAY,
            StatusCode::GATEWAY_TIMEOUT,
        ] {
            assert_eq!(failure_level(&class(status)), Level::ERROR, "{status}");
        }
        assert_eq!(
            failure_level(&ServerErrorsFailureClass::Error("body".into())),
            Level::ERROR
        );
    }

    async fn panicking() -> &'static str {
        panic!("boom")
    }

    fn app() -> Router {
        let router = Router::new()
            .route("/ok", get(|| async { "ok" }))
            .route(
                "/request-id",
                get(|axum::Extension(id): axum::Extension<RequestId>| async move { id.0 }),
            )
            .route(
                "/slow",
                get(|| async {
                    tokio::time::sleep(Duration::from_secs(5)).await;
                    "late"
                }),
            )
            .route("/panic", get(panicking))
            .route("/echo", post(|body: String| async move { body }))
            .route("/big", get(|| async { "x".repeat(10_000) }));
        with_common_layers(router, &http_config(), Surface::Public)
    }

    async fn send(request: axum::http::Request<Body>) -> (Response, serde_json::Value) {
        let response = app().oneshot(request).await.unwrap();
        let (parts, body) = response.into_parts();
        let bytes = body.collect().await.unwrap().to_bytes();
        let json = serde_json::from_slice(&bytes).unwrap_or(serde_json::Value::Null);
        (Response::from_parts(parts, Body::from(bytes)), json)
    }

    fn get_req(uri: &str) -> axum::http::Request<Body> {
        axum::http::Request::get(uri).body(Body::empty()).unwrap()
    }

    #[tokio::test]
    async fn adds_request_id_and_security_header() {
        let request = axum::http::Request::get("/request-id")
            .header("x-request-id", "forged")
            .body(Body::empty())
            .unwrap();
        let response = app().oneshot(request).await.unwrap();
        let header_id = response.headers()[REQUEST_ID_HEADER]
            .to_str()
            .unwrap()
            .to_owned();
        assert_ne!(header_id, "forged");
        assert!(uuid::Uuid::parse_str(&header_id).is_ok());
        assert_eq!(
            response.headers()[header::X_CONTENT_TYPE_OPTIONS],
            "nosniff"
        );
        let body = response.into_body().collect().await.unwrap().to_bytes();
        assert_eq!(body, header_id.as_bytes());
    }

    #[tokio::test]
    async fn unknown_routes_and_methods_get_json_errors() {
        let (response, json) = send(get_req("/missing")).await;
        assert_eq!(response.status(), StatusCode::NOT_FOUND);
        assert_eq!(json["error"]["code"], "not_found");
        security::assert_security_headers(response.headers(), "404");

        let (response, json) = send(
            axum::http::Request::delete("/ok")
                .body(Body::empty())
                .unwrap(),
        )
        .await;
        assert_eq!(response.status(), StatusCode::METHOD_NOT_ALLOWED);
        assert_eq!(json["error"]["code"], "method_not_allowed");
        assert!(response.headers().contains_key(header::ALLOW));
        security::assert_security_headers(response.headers(), "405");
    }

    #[tokio::test]
    async fn timeouts_are_reported_as_json() {
        let (response, json) = send(get_req("/slow")).await;
        assert_eq!(response.status(), StatusCode::GATEWAY_TIMEOUT);
        assert_eq!(json["error"]["code"], "timeout");
        security::assert_security_headers(response.headers(), "504");
    }

    #[tokio::test]
    async fn panics_become_500() {
        let (response, json) = send(get_req("/panic")).await;
        assert_eq!(response.status(), StatusCode::INTERNAL_SERVER_ERROR);
        assert_eq!(json["error"]["code"], "internal_error");
        security::assert_security_headers(response.headers(), "500");
    }

    #[tokio::test]
    async fn bodies_over_the_limit_are_rejected() {
        let request = axum::http::Request::post("/echo")
            .body(Body::from("y".repeat(2048)))
            .unwrap();
        let (response, json) = send(request).await;
        assert_eq!(response.status(), StatusCode::PAYLOAD_TOO_LARGE);
        assert_eq!(json["error"]["code"], "payload_too_large");
        security::assert_security_headers(response.headers(), "413");
        assert_eq!(response.headers()[header::CACHE_CONTROL], "no-store");

        let request = axum::http::Request::post("/echo")
            .body(Body::from("small"))
            .unwrap();
        let (response, _) = send(request).await;
        assert_eq!(response.status(), StatusCode::OK);
    }

    #[tokio::test]
    async fn responses_are_compressed_on_demand() {
        let request = axum::http::Request::get("/big")
            .header(header::ACCEPT_ENCODING, "gzip")
            .body(Body::empty())
            .unwrap();
        let response = app().oneshot(request).await.unwrap();
        assert_eq!(response.headers()[header::CONTENT_ENCODING], "gzip");
        security::assert_security_headers(response.headers(), "compressed");
    }
}
